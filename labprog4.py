a = int(input("Enter the first number:"))
b = int(input("Enter the second number:"))

c = a + b
d = a - b
e = a * b
f = a / b

print(f"Addition of two number {a} + {b} = {c}")
print(f"Substraction of two number {a} - {b} = {d}")
print(f"Multiplication of two number {a} * {b} = {e}")
print(f"Division of two number {a} / {b} = {f}")